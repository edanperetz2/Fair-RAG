"""
Regenerates experiment_runs/INDEX.md: one row per run directory, parsed from
each manifest.json, so the ~500 flat directories under experiment_runs/ are
browsable on GitHub without opening folders one at a time.

Usage:
    python experiments/generate_run_index.py
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.realpath(__file__)))
sys.path.insert(0, ROOT)

from analysis.labels import format_rerank_label

RUNS_DIR = os.path.join(ROOT, "experiment_runs")
OUT_PATH = os.path.join(RUNS_DIR, "INDEX.md")

COLUMNS = [
    "lamp", "generator", "ranker", "setting", "top_k", "num_queries",
    "offset", "status", "completed", "run_dir",
]


def load_row(run_dir_name):
    manifest_path = os.path.join(RUNS_DIR, run_dir_name, "manifest.json")
    if not os.path.exists(manifest_path):
        return None
    with open(manifest_path, encoding="utf-8") as fh:
        m = json.load(fh)
    cfg = m["config"]
    d, r, rr, g = cfg["dataset"], cfg["retrieval"], cfg["rerank"], cfg["generation"]
    setting = format_rerank_label(
        {"rerank_method": rr.get("method"), "pl_alpha": rr.get("pl_alpha"), "mmr_lambda": rr.get("mmr_lambda")}
    )
    num_queries = d.get("num_queries")
    return {
        "lamp": d["lamp_num"],
        "generator": g["generator_name"],
        "ranker": r["ranker"],
        "setting": setting,
        "top_k": r["top_k"],
        "num_queries": num_queries if num_queries is not None else "all",
        "offset": d.get("query_offset", 0),
        "status": m.get("status", "?"),
        "completed": m.get("n_queries_completed", "?"),
        "run_dir": run_dir_name,
    }


def main():
    rows = []
    for name in sorted(os.listdir(RUNS_DIR)):
        if not os.path.isdir(os.path.join(RUNS_DIR, name)):
            continue
        row = load_row(name)
        if row is not None:
            rows.append(row)

    rows.sort(key=lambda r: (r["lamp"], r["generator"], r["ranker"], r["offset"], r["setting"]))

    lines = [
        "<!-- Auto-generated by experiments/generate_run_index.py - do not hand-edit. -->",
        "# experiment_runs/ index",
        "",
        f"{len(rows)} run directories. See `README.md` in this folder for the naming "
        "convention and directory-count explanation. This table is sorted by "
        "(LaMP task, generator, ranker, query_offset, setting) for browsing - use "
        "your browser's find-in-page to filter.",
        "",
        "| LaMP | Generator | Ranker | Setting | k | num_queries | offset | status | completed | run_dir |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for row in rows:
        lines.append(
            f"| {row['lamp']} | {row['generator']} | {row['ranker']} | {row['setting']} "
            f"| {row['top_k']} | {row['num_queries']} | {row['offset']} | {row['status']} "
            f"| {row['completed']} | `{row['run_dir']}` |"
        )

    with open(OUT_PATH, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")

    print(f"Wrote {len(rows)} rows to {OUT_PATH}")


if __name__ == "__main__":
    main()
