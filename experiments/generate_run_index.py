"""
Regenerates experiment_runs/INDEX.md: one row per run directory, parsed from
each manifest.json, so the nested experiment_runs/{generator}/lamp{N}/
{ranker}/ tree is browsable as one sortable table alongside folder browsing.

Uses framework.cross_run_analysis.list_run_dirs, which recursively finds
every directory containing manifest.json regardless of nesting depth.

Usage:
    python experiments/generate_run_index.py
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.realpath(__file__)))
sys.path.insert(0, ROOT)

from framework.cross_run_analysis import list_run_dirs
from analysis.labels import format_rerank_label

RUNS_DIR = os.path.join(ROOT, "experiment_runs")
OUT_PATH = os.path.join(RUNS_DIR, "INDEX.md")


def load_row(run_dir):
    manifest_path = os.path.join(run_dir, "manifest.json")
    if not os.path.exists(manifest_path):
        return None
    with open(manifest_path, encoding="utf-8") as fh:
        m = json.load(fh)
    cfg = m["config"]
    d, r, rr, g = cfg["dataset"], cfg["retrieval"], cfg["rerank"], cfg["generation"]
    setting = format_rerank_label(
        {"rerank_method": rr.get("method"), "pl_alpha": rr.get("pl_alpha"), "mmr_lambda": rr.get("mmr_lambda")}
    )
    num_queries = d.get("num_queries")
    rel_path = os.path.relpath(run_dir, RUNS_DIR).replace(os.sep, "/")
    return {
        "lamp": d["lamp_num"],
        "generator": g["generator_name"],
        "ranker": r["ranker"],
        "setting": setting,
        "top_k": r["top_k"],
        "num_queries": num_queries if num_queries is not None else "all",
        "offset": d.get("query_offset", 0),
        "status": m.get("status", "?"),
        "completed": m.get("n_queries_completed", "?"),
        "rel_path": rel_path,
    }


def main():
    rows = []
    for run_dir in list_run_dirs():
        row = load_row(run_dir)
        if row is not None:
            rows.append(row)

    rows.sort(key=lambda r: (r["generator"], r["lamp"], r["ranker"], r["setting"]))

    lines = [
        "<!-- Auto-generated by experiments/generate_run_index.py - do not hand-edit. -->",
        "# experiment_runs/ index",
        "",
        f"{len(rows)} run directories, one per (generator, LaMP task, ranker, rerank "
        "setting) - see `README.md` in this folder for the directory-naming and "
        "nesting convention. Sorted by (generator, LaMP task, ranker, setting); use "
        "your browser's find-in-page to filter.",
        "",
        "| Generator | LaMP | Ranker | Setting | k | queries | status | path |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for row in rows:
        lines.append(
            f"| {row['generator']} | {row['lamp']} | {row['ranker']} | {row['setting']} "
            f"| {row['top_k']} | {row['completed']}/{row['num_queries']} | {row['status']} "
            f"| `{row['rel_path']}` |"
        )

    with open(OUT_PATH, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")

    print(f"Wrote {len(rows)} rows to {OUT_PATH}")


if __name__ == "__main__":
    main()
